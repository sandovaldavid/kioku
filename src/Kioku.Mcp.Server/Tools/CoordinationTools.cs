using System.ComponentModel;
using System.Text.Json;
using Kioku.Mcp.Server.Domain.Coordination;
using Kioku.Mcp.Server.Services;
using ModelContextProtocol.Server;

namespace Kioku.Mcp.Server.Tools;

/// <summary>
/// Thin MCP adapters for the opt-in durable coordination application boundary.
/// </summary>
[McpServerToolType]
public sealed class CoordinationTools(ICoordinationService coordination)
{
    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.SnakeCaseLower,
        WriteIndented = true,
    };

    [McpServerTool, Description(
        "Initializes a durable coordination run and work item. Empty IDs are generated by the server; " +
        "the operation is idempotent when the same work_item_id and transition_id are retried.")]
    public Task<string> create_coordination_work_item(
        [Description("Project or workflow name associated with the work item.")] string project,
        [Description("Run identity. Empty generates a UUIDv7 run_id.")] string run_id = "",
        [Description("Work-item identity. Empty generates a UUIDv7 work_item_id.")] string work_item_id = "",
        [Description("Attempt identity. Empty generates a UUIDv7 attempt_id.")] string attempt_id = "",
        [Description("Optional durable work-session identity associated with the item.")] string session_id = "",
        [Description("Untrusted diagnostic agent label.")] string agent = "",
        [Description("Comma-separated note: or logical: resource keys protected by the work item.")] string resource_scope = "",
        [Description("Bounded human-readable checkpoint summary.")] string summary = "",
        [Description("Idempotency key for retrying initialization. Empty derives a stable key from work_item_id.")] string transition_id = "",
        McpServer? server = null,
        CancellationToken cancellationToken = default) =>
        ExecuteAsync(() => coordination.CreateWorkItemAsync(
            new CoordinationCreateWorkItemRequest
            {
                RunId = run_id,
                WorkItemId = work_item_id,
                Project = project,
                AttemptId = attempt_id,
                SessionId = session_id,
                Agent = agent,
                ClientName = server?.ClientInfo?.Name,
                ResourceScope = SplitList(resource_scope),
                Summary = summary,
                TransitionId = transition_id,
            },
            cancellationToken));

    [McpServerTool, Description(
        "Returns the current durable coordination projection, active claims, and unresolved conflicts " +
        "for one work item.")]
    public Task<string> get_coordination_work_item(
        [Description("Run identity.")] string run_id,
        [Description("Work-item identity.")] string work_item_id,
        CancellationToken cancellationToken = default) =>
        ExecuteAsync(() => coordination.GetWorkItemAsync(run_id, work_item_id, cancellationToken));

    [McpServerTool, Description("Lists durable coordination work items with optional run, project, and state filters.")]
    public Task<string> list_coordination_work_items(
        [Description("Optional run identity filter.")] string run_id = "",
        [Description("Optional project filter.")] string project = "",
        [Description("Optional state filter: pending, claimed, running, blocked, partial, failed, stale, completed, or canceled.")] string state = "",
        [Description("Number of matching items to skip.")] int offset = 0,
        [Description("Maximum items to return.")] int limit = 20,
        CancellationToken cancellationToken = default) =>
        ExecuteAsync(() => coordination.ListWorkItemsAsync(
            EmptyToNull(run_id),
            EmptyToNull(project),
            EmptyToNull(state),
            offset,
            limit,
            cancellationToken));

    [McpServerTool, Description("Lists durable coordination runs with state counts and last-update timestamps.")]
    public Task<string> list_coordination_runs(
        [Description("Number of matching runs to skip.")] int offset = 0,
        [Description("Maximum runs to return.")] int limit = 20,
        CancellationToken cancellationToken = default) =>
        ExecuteAsync(() => coordination.ListRunsAsync(offset, limit, cancellationToken));

    [McpServerTool, Description(
        "Transitions a work item through the durable state machine. State-changing work normally " +
        "requires the current claim_id and fence_generation; expected_state_version prevents stale reads.")]
    public Task<string> transition_coordination_work_item(
        [Description("Run identity.")] string run_id,
        [Description("Work-item identity.")] string work_item_id,
        [Description("Target state: pending, claimed, running, blocked, partial, failed, stale, completed, or canceled.")] string next_state,
        [Description("Optional explicit event type; the server derives and validates it when empty.")] string event_type = "",
        [Description("Attempt identity; empty uses the current projection.")] string attempt_id = "",
        [Description("Session identity; empty uses the current projection.")] string session_id = "",
        [Description("Idempotency key for the transition. Empty generates a one-shot key.")] string transition_id = "",
        [Description("Expected current state_version. Negative keeps compatibility mode without a version precondition.")] long expected_state_version = -1,
        [Description("Current claim ID protecting the transition.")] string claim_id = "",
        [Description("Current claim fence generation protecting the transition.")] long fence_generation = 0,
        [Description("Untrusted diagnostic agent label.")] string agent = "",
        [Description("Human-readable transition reason or blocker description.")] string reason = "",
        [Description("Safe outcome summary for partial, failed, completed, or canceled states.")] string outcome = "",
        [Description("Stable safe error code for failed or blocked work.")] string error_code = "",
        [Description("Safe reference to a result or resolution artifact.")] string result_reference = "",
        [Description("Safe reference to progress or an in-flight result.")] string progress_reference = "",
        McpServer? server = null,
        CancellationToken cancellationToken = default) =>
        ExecuteAsync(() => coordination.TransitionAsync(
            new CoordinationTransitionRequest
            {
                RunId = run_id,
                WorkItemId = work_item_id,
                NextState = next_state,
                EventType = EmptyToNull(event_type),
                AttemptId = EmptyToNull(attempt_id),
                SessionId = EmptyToNull(session_id),
                TransitionId = EmptyToNull(transition_id),
                ExpectedStateVersion = expected_state_version >= 0 ? expected_state_version : null,
                ClaimId = EmptyToNull(claim_id),
                FenceGeneration = fence_generation > 0 ? fence_generation : null,
                Agent = EmptyToNull(agent),
                ClientName = server?.ClientInfo?.Name,
                Reason = EmptyToNull(reason),
                Outcome = EmptyToNull(outcome),
                ErrorCode = EmptyToNull(error_code),
                ResultReference = EmptyToNull(result_reference),
                ProgressReference = EmptyToNull(progress_reference),
            },
            cancellationToken));

