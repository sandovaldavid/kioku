    [McpServerTool, Description("Lists stale work items and expired claims that require recovery.")]
    public async Task<string> list_stale_coordination_work(
        [Description("Optional run identity filter.")] string run_id = "",
        [Description("Number of stale items to skip.")] int offset = 0,
        [Description("Maximum stale items to return.")] int limit = 20,
        CancellationToken cancellationToken = default)
    {
        try
        {
            var work = await coordination.ListWorkItemsAsync(
                EmptyToNull(run_id),
                state: CoordinationStates.Stale,
                offset: offset,
                limit: limit,
                cancellationToken: cancellationToken);
            var claims = await coordination.ListClaimsAsync(
                EmptyToNull(run_id),
                status: CoordinationClaimStatuses.Expired,
                offset: 0,
                limit: limit,
                cancellationToken: cancellationToken);
            return Serialize(new { work_items = work, expired_claims = claims });
        }
        catch (CoordinationOperationException exception)
        {
            return exception.ToToolError();
        }
    }

