    private static async Task<string> ExecuteAsync<T>(Func<Task<T>> operation)
    {
        try
        {
            return Serialize(await operation().ConfigureAwait(false));
        }
        catch (CoordinationOperationException exception)
        {
            return exception.ToToolError();
        }
        catch (CoordinationClaimException exception)
        {
            return Error(
                exception.Code.ToUpperInvariant(),
                "The coordination claim operation was rejected.",
                "Read the current claim and work-item projection before retrying.");
        }
        catch (CoordinationStoreException)
        {
            return Error(
                CoordinationOperationErrorCodes.CorruptHistory,
                "The coordination history could not be read safely.",
                "Preserve the coordination files and inspect the history before retrying.");
        }
        catch (CoordinationConflictStoreException)
        {
            return Error(
                CoordinationOperationErrorCodes.CorruptHistory,
                "The durable coordination conflict record could not be read safely.",
                "Preserve the coordination files and inspect the conflict record before retrying.");
        }
    }

    private static string Serialize<T>(T value) => JsonSerializer.Serialize(value, JsonOptions);

    private static string Error(string code, string message, string recovery) =>
        $"[error:{code}] {JsonSerializer.Serialize(new { code, message, recovery_action = recovery })}";

    private static string? EmptyToNull(string? value) =>
        string.IsNullOrWhiteSpace(value) ? null : value.Trim();

    private static IReadOnlyList<string> SplitList(string? value) =>
        string.IsNullOrWhiteSpace(value)
            ? []
            : value.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
}
