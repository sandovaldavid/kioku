        [Description("Idempotency key for the claim operation.")] string transition_id,
        [Description("Lease duration in seconds, from 1 through 3600.")] int lease_seconds = 30,
        [Description("Untrusted diagnostic agent label.")] string agent = "",
        McpServer? server = null,
