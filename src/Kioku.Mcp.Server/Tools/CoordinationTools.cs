    public Task<string> resolve_coordination_conflict(
        [Description("Conflict identity.")] string conflict_id,
        [Description("Resolution status: resolved or ignored.")] string status,
        [Description("Bounded resolution or acknowledgement note.")] string resolution,
        [Description("Untrusted diagnostic agent label.")] string agent = "",
        [Description("Optional durable session identity recording the resolution.")] string session_id = "",
        McpServer? server = null,
        CancellationToken cancellationToken = default) =>
        ExecuteAsync(() => coordination.ResolveConflictAsync(
